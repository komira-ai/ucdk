//! The TypeScript target: one module per proto package, the wire primitives they share, and the
//! typed resource templates.
//!
//! Files written, relative to the SDK's package directory:
//!
//! - `src/generated/wire.ts`: varint and length-delimited primitives, and the `Message` base
//!   class; the same text for every proto;
//! - `src/generated/<package>.ts` (`ucdk.api.v1` is `ucdk_api_v1.ts`): the enums and message
//!   classes of one package, and of every package they refer to (`google_protobuf.ts` holds the
//!   `Duration` the resource messages use);
//! - `src/generated/resources.ts`: the typed templates (when the protos declare `Resource`).
//!
//! Node runs the files as they are, by stripping the types, so only syntax that is nothing but
//! types is used, and imports name their `.ts` files.

mod message;
mod names;
mod templates;
mod types;

use std::collections::BTreeSet;

use prost_reflect::{DescriptorPool, EnumDescriptor, MessageDescriptor};

use crate::model::{Module, collect, imports};
use crate::names::{local_name, module_of};
use crate::{Error, File};

/// The directory the generated files are written to, inside the SDK package.
pub const GENERATED_DIR: &str = "src/generated";

const WIRE: &str = include_str!("wire.ts");
pub(super) const HEADER: &str = "// Generated by `cargo xtask gen-sdk` from the ucdk protos. Do not edit.\n// SPDX-License-Identifier: Apache-2.0\n";

fn import(module: &str) -> String {
    format!("import * as {module} from \"./{module}.ts\";")
}

fn module_text(package: &str, module: &Module) -> Result<String, Error> {
    let mut names = BTreeSet::new();
    let declared = module
        .enums
        .iter()
        .map(EnumDescriptor::full_name)
        .chain(module.messages.iter().map(MessageDescriptor::full_name));
    for full in declared {
        if !names.insert(local_name(full, package)) {
            return Err(Error::refused(
                full,
                "two types have the same TypeScript name",
            ));
        }
    }
    for m in &module.messages {
        let init = format!("{}Init", local_name(m.full_name(), package));
        if !names.insert(init) {
            return Err(Error::refused(
                m.full_name(),
                "the name of its constructor's object is the name of another type",
            ));
        }
    }
    let mut out: Vec<String> = HEADER.lines().map(str::to_owned).collect();
    out.push(format!(
        "/** The messages and enums of the proto package `{package}`. */"
    ));
    out.push(String::new());
    out.push(import("wire"));
    out.extend(imports(package, module).iter().map(|m| import(m)));
    for e in &module.enums {
        out.extend(message::enum_def(e));
    }
    for m in &module.messages {
        out.extend(message::class(m, package)?);
    }
    Ok(out.join("\n") + "\n")
}

fn file(name: &str, text: String) -> File {
    File {
        path: format!("{GENERATED_DIR}/{name}"),
        text,
    }
}

/// The TypeScript SDK's generated files for the messages of `files` (names inside the pool) and
/// everything they refer to.
pub fn generate(pool: &DescriptorPool, files: &[&str]) -> Result<Vec<File>, Error> {
    let modules = collect(pool, files)?;
    let names: Vec<String> = modules.keys().map(|p| module_of(p)).collect();
    let resources = templates::generate(pool, &names)?;
    let mut out = vec![file("wire.ts", WIRE.to_owned())];
    for (package, module) in &modules {
        out.push(file(
            &format!("{}.ts", module_of(package)),
            module_text(package, module)?,
        ));
    }
    if let Some(text) = resources {
        out.push(file("resources.ts", text));
    }
    Ok(out)
}
