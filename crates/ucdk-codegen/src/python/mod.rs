//! The Python target: one module per proto package, the wire primitives they share, and the
//! typed resource templates.
//!
//! Files written, relative to the SDK's package directory:
//!
//! - `ucdk/generated/_wire.py`: varint and length-delimited primitives, and the `Message` base
//!   class; the same text for every proto;
//! - `ucdk/generated/<package>.py` (`ucdk.api.v1` is `ucdk_api_v1.py`): the enums and message
//!   classes of one package, and of every package they refer to (`google_protobuf.py` holds the
//!   `Duration` the resource messages use);
//! - `ucdk/generated/resources.py`: the typed templates (when the protos declare `Resource`);
//! - `ucdk/generated/__init__.py`.

mod message;
mod templates;
mod types;

use std::collections::{BTreeMap, BTreeSet};

use prost_reflect::{DescriptorPool, EnumDescriptor, Kind, MessageDescriptor};

use crate::names::{local_name, module_of};
use crate::{Error, File};

/// The directory the generated files are written to, inside the SDK package.
pub const GENERATED_DIR: &str = "ucdk/generated";

const WIRE: &str = include_str!("wire.py");
pub(super) const HEADER: &str = "# Generated by `cargo xtask gen-sdk` from the ucdk protos. Do not edit.\n# SPDX-License-Identifier: Apache-2.0\n";

/// The messages and enums of one proto package.
#[derive(Default)]
struct Module {
    messages: Vec<MessageDescriptor>,
    enums: Vec<EnumDescriptor>,
}

#[derive(Default)]
struct Collected {
    seen: BTreeSet<String>,
    modules: BTreeMap<String, Module>,
    /// Every message in the order it was found, to follow its fields.
    queue: Vec<MessageDescriptor>,
}

impl Collected {
    fn enum_(&mut self, e: &EnumDescriptor) {
        if self.seen.insert(e.full_name().to_owned()) {
            let module = self.modules.entry(e.package_name().to_owned()).or_default();
            module.enums.push(e.clone());
        }
    }

    /// Adds a message, its nested messages and its nested enums; a map entry is not a message of
    /// its own.
    fn message(&mut self, m: &MessageDescriptor) {
        if m.is_map_entry() || !self.seen.insert(m.full_name().to_owned()) {
            return;
        }
        let module = self.modules.entry(m.package_name().to_owned()).or_default();
        module.messages.push(m.clone());
        self.queue.push(m.clone());
        for e in m.child_enums() {
            self.enum_(&e);
        }
        for child in m.child_messages() {
            self.message(&child);
        }
    }

    /// Adds what a field refers to.
    fn reference(&mut self, kind: &Kind) {
        match kind {
            Kind::Message(m) if m.is_map_entry() => {
                self.reference(&m.map_entry_value_field().kind());
            }
            Kind::Message(m) => self.message(m),
            Kind::Enum(e) => self.enum_(e),
            _ => {}
        }
    }
}

/// The messages of `files`, then whatever else they refer to, grouped by package.
fn collect(pool: &DescriptorPool, files: &[&str]) -> Result<BTreeMap<String, Module>, Error> {
    let mut found = Collected::default();
    for name in files {
        let Some(file) = pool.get_file_by_name(name) else {
            return Err(Error::Missing((*name).to_owned()));
        };
        for e in file.enums() {
            found.enum_(&e);
        }
        for m in file.messages() {
            found.message(&m);
        }
    }
    let mut at = 0;
    while at < found.queue.len() {
        let message = found.queue[at].clone();
        at += 1;
        for field in message.fields() {
            found.reference(&field.kind());
        }
    }
    Ok(found.modules)
}

/// The packages whose types the messages of `module` refer to.
fn imports(package: &str, module: &Module) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    for field in module.messages.iter().flat_map(MessageDescriptor::fields) {
        let kind = field.kind();
        let kind = match &kind {
            Kind::Message(m) if m.is_map_entry() => m.map_entry_value_field().kind(),
            _ => kind,
        };
        let other = match &kind {
            Kind::Message(m) => m.package_name(),
            Kind::Enum(e) => e.package_name(),
            _ => package,
        };
        if other != package {
            out.insert(module_of(other));
        }
    }
    out
}

fn module_text(package: &str, module: &Module) -> Result<String, Error> {
    let mut names = BTreeSet::new();
    let declared = module
        .enums
        .iter()
        .map(EnumDescriptor::full_name)
        .chain(module.messages.iter().map(MessageDescriptor::full_name));
    for full in declared {
        if !names.insert(local_name(full, package)) {
            return Err(Error::refused(full, "two types have the same Python name"));
        }
    }
    let mut out: Vec<String> = HEADER.lines().map(str::to_owned).collect();
    out.push(format!(
        "\"\"\"The messages and enums of the proto package `{package}`.\"\"\""
    ));
    out.push(String::new());
    out.push("from __future__ import annotations".to_owned());
    out.push(String::new());
    out.push("import enum".to_owned());
    out.push("from typing import Any, Iterable, Mapping, Optional".to_owned());
    out.push(String::new());
    out.push("from . import _wire".to_owned());
    out.extend(
        imports(package, module)
            .iter()
            .map(|m| format!("from . import {m}")),
    );
    for e in &module.enums {
        out.extend(message::enum_class(e));
    }
    for m in &module.messages {
        out.extend(message::class(m, package)?);
    }
    Ok(out.join("\n") + "\n")
}

fn file(name: &str, text: String) -> File {
    File {
        path: format!("{GENERATED_DIR}/{name}"),
        text,
    }
}

/// The Python SDK's generated files for the messages of `files` (names inside the pool) and
/// everything they refer to.
pub fn generate(pool: &DescriptorPool, files: &[&str]) -> Result<Vec<File>, Error> {
    let modules = collect(pool, files)?;
    let names: Vec<String> = modules.keys().map(|p| module_of(p)).collect();
    let resources = templates::generate(pool, &names)?;
    let mut out = vec![
        file(
            "__init__.py",
            format!("{HEADER}\"\"\"The generated part of the ucdk SDK.\"\"\"\n"),
        ),
        file("_wire.py", WIRE.to_owned()),
    ];
    for (package, module) in &modules {
        out.push(file(
            &format!("{}.py", module_of(package)),
            module_text(package, module)?,
        ));
    }
    if let Some(text) = resources {
        out.push(file("resources.py", text));
    }
    Ok(out)
}
